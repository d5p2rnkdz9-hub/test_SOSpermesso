#!/usr/bin/env node
/**
 * Builds src/lib/permits-kb.generated.ts: for each permit, the Q&A of its
 * sospermesso.it page as plain text (from ../Sito_Nuovo/_cache/permits-it.json),
 * plus document checklists and costs. Served to the PRO chatbot by the
 * `scheda_permesso` tool (src/lib/chat-pro.ts) — one permit per call, so the
 * whole KB never rides in the prompt.
 *
 *   node scripts/generate-permits-kb.js
 *
 * Same conversion rules as Sito_Nuovo/scripts/build-chatbot-kb.js, without cheerio.
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', '..', 'Sito_Nuovo', '_cache', 'permits-it.json');
const DEST = path.join(__dirname, '..', 'src', 'lib', 'permits-kb.generated.ts');
const SITE_URL = 'https://www.sospermesso.it';

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', rsquo: '’', lsquo: '‘', ldquo: '“', rdquo: '”', egrave: 'è', eacute: 'é', agrave: 'à', ograve: 'ò', ugrave: 'ù', igrave: 'ì' };

function htmlToText(html) {
  if (!html) return '';
  return String(html)
    .replace(/<li[^>]*>/gi, '\n- ')
    .replace(/<\/(p|ul|ol|li|h[1-6]|blockquote|tr|div|section)>/gi, '\n')
    .replace(/<(br|hr)\s*\/?>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&([a-z]+);/gi, (m, e) => ENTITIES[e.toLowerCase()] ?? m)
    .replace(/[ \t]+/g, ' ')
    .replace(/ *\n */g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

const isDocumentsSection = (q) => /documenti/i.test(q || '') && /serv|necessar|lista/i.test(q || '');
const cost = (v) => (v === null || v === undefined || v === '' ? null : `${v} €`);

function buildBlock(p) {
  const lines = [`# ${p.tipo}`, `Categoria: ${p.categoria || 'n/d'}`, `Scheda pubblica: ${SITE_URL}/permesso-${p.slug}.html`, ''];
  for (const s of p.sections || []) {
    if (isDocumentsSection(s.question)) continue;
    const text = htmlToText(s.content);
    if (!text) continue;
    lines.push(`## ${s.question}`, text, '');
  }
  const docs = (label, list, method, c1, c2, c3) => {
    if (!Array.isArray(list) || list.length === 0) return;
    lines.push(`## ${label} (modalità: ${method || 'n/d'})`);
    for (const d of list) lines.push(`- ${d}`);
    const costs = [];
    if (cost(c1)) costs.push(`bollettino postale ${cost(c1)}`);
    if (cost(c2)) costs.push(`bollettino alternativo ${cost(c2)}`);
    if (cost(c3)) costs.push(`marca da bollo ${cost(c3)}`);
    if (costs.length) lines.push(`Costi: ${costs.join(', ')}.`);
    lines.push('');
  };
  docs('Documenti per la prima richiesta', p.primoDocuments, p.primoMethod, p.costBollettinoPrimo, p.costBollettinoAltPrimo, p.costMarcaBolloPrimo);
  if (p.rinnovoNotApplicable) lines.push('## Rinnovo', 'Il rinnovo non è previsto per questo permesso.', '');
  else docs('Documenti per il rinnovo', p.rinnovoDocuments, p.rinnovoMethod, p.costBollettinoRinnovo, p.costBollettinoAltRinnovo, p.costMarcaBolloRinnovo);
  const notes = htmlToText(p.docNotes);
  if (notes) lines.push('## Note sui documenti', notes, '');
  return lines.join('\n').trim();
}

const permits = JSON.parse(fs.readFileSync(SRC, 'utf-8')).filter((p) => p.slug && p.tipo && !p.isPlaceholder);
const kb = {};
for (const p of permits) kb[p.slug] = buildBlock(p);

const out = `/**
 * AUTO-GENERATED by scripts/generate-permits-kb.js — DO NOT EDIT.
 * Source: Sito_Nuovo/_cache/permits-it.json (${permits.length} permits). Server-only.
 */
import 'server-only';

/* eslint-disable */
export const permitsKb: Record<string, string> = ${JSON.stringify(kb, null, 2)};
`;
fs.writeFileSync(DEST, out);
const kbChars = Object.values(kb).reduce((n, t) => n + t.length, 0);
console.log(`[generate-permits-kb] ${permits.length} permits, ${(kbChars / 1024).toFixed(0)} KB → ${path.relative(process.cwd(), DEST)}`);
